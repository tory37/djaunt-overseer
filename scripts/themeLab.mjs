// Dev only: builds the shipped Overseer themes ("Current") and each proposal layer into theme-lab/lab-data.js for theme-lab/index.html.
import * as fs from "fs";
import { THEMES, MIN_TEXT_CONTRAST, SURFACE_CHROMA, SURFACE_STEP, buildTheme, contrastChecks, contrastFailures, shippedPalette } from "./themes.mjs";
import { PROPOSAL_LAYERS } from "./themeLabProposal.mjs";

const LAB_DATA_PATH = "theme-lab/lab-data.js";
const PACKAGE_JSON_PATH = "package.json";
const OVERSEER_COLOR_PREFIX = "overseer.";
const identity = (variantName, palette, value) => value;

// Runs the shipped generator on the layered base palette, then applies each layer's color and token overrides.
function buildMode(variantName, basePalette, layers) {
  const layeredBase = layers.reduce((current, layer) => (layer.palette ?? ((name, value) => value))(variantName, current), basePalette);
  const palette = shippedPalette(layeredBase);
  const built = buildTheme(palette);
  const colors = layers.reduce((current, layer) => (layer.colors ?? identity)(variantName, palette, current), built.colors);
  const tokens = layers.reduce((current, layer) => (layer.tokens ?? identity)(variantName, palette, current), {
    tokenColors: built.tokenColors,
    semanticTokenColors: built.semanticTokenColors,
  });
  const failures = contrastFailures(variantName, palette, colors);
  const lowest = contrastChecks(palette, colors).reduce((min, check) => (check.ratio < min.ratio ? check : min));
  return {
    palette,
    colors,
    tokenColors: tokens.tokenColors,
    semanticTokenColors: tokens.semanticTokenColors,
    contrast: { lowestPair: { what: lowest.what, ratio: Number(lowest.ratio.toFixed(2)) }, failures },
  };
}

const MODES = [
  { id: "current", label: "Current", layers: [] },
  ...PROPOSAL_LAYERS.map((layer, index) => ({ id: layer.id, label: layer.label, layers: PROPOSAL_LAYERS.slice(0, index + 1) })),
];

const variants = {};
const failuresByMode = {};
for (const mode of MODES) {
  console.log(`\n${mode.label}`);
  failuresByMode[mode.id] = [];
  for (const [variantName, palette] of Object.entries(THEMES)) {
    const built = buildMode(variantName, palette, mode.layers);
    variants[variantName] ??= { label: palette.label, kind: palette.kind };
    variants[variantName][mode.id] = built;
    failuresByMode[mode.id].push(...built.contrast.failures);
  }
}

// The lab tags any mock element whose color the extension can't deliver: an overseer id it doesn't contribute,
// or a key the shipped themes don't set and the lab doesn't list as a VS Code built-in.
const contributedColorIds = JSON.parse(fs.readFileSync(PACKAGE_JSON_PATH, "utf8")).contributes.colors.map((color) => color.id);
const shippedBuiltInColorIds = [
  ...new Set(Object.values(variants).flatMap((variant) => Object.keys(variant.current.colors).filter((colorId) => !colorId.startsWith(OVERSEER_COLOR_PREFIX)))),
];

const labData = {
  generatedAt: new Date().toISOString(),
  modes: MODES.map(({ id, label }) => ({ id, label })),
  surfaceStep: SURFACE_STEP,
  surfaceChroma: SURFACE_CHROMA, minTextContrast: MIN_TEXT_CONTRAST, contributedColorIds, shippedBuiltInColorIds, variants };
fs.writeFileSync(
  LAB_DATA_PATH,
  ["// Generated by scripts/themeLab.mjs (npm run theme-lab). Do not edit by hand.", `window.THEME_LAB = ${JSON.stringify(labData, null, 2)};`, ""].join("\n"),
);

console.log("");
for (const [mode, failures] of Object.entries(failuresByMode)) {
  if (failures.length > 0) console.error(`${mode}: contrast under ${MIN_TEXT_CONTRAST}:1:\n  ${failures.join("\n  ")}`);
  else console.log(`${mode}: all text colors meet ${MIN_TEXT_CONTRAST}:1.`);
}
console.log(`Wrote ${LAB_DATA_PATH}. Open theme-lab/index.html in a browser.`);
const proposalFailed = PROPOSAL_LAYERS.some((layer) => failuresByMode[layer.id].length > 0);
if (proposalFailed) process.exit(1);
